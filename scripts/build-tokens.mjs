// Generates src/styles/tokens.css from the design system's tokens.json (design guide §0.1: never hand-copy a value).
// Any element with data-theme="dark" takes the dark set, so a single band of the page can be dark.
//   node scripts/build-tokens.mjs [path/to/tokens.json]
// The default path is the copy checked in beside this script; refresh it from the design system before running.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const source = resolve(process.argv[2] ?? new URL("./tokens.json", import.meta.url).pathname);
const tokens = JSON.parse(readFileSync(source, "utf8"));

const value = (entry, theme) =>
	typeof entry.value === "string" ? entry.value : (entry.value[theme] ?? entry.value.light);
const lines = (theme) => [
	...tokens.color.tokens.map((t) => `  --${t.name}: ${value(t, theme)};`),
	...tokens.shadow.tokens.map((t) => `  --${t.name}: ${value(t, theme)};`),
];
const fixed = [
	...tokens.spacing.tokens.map((t) => `  --${t.name}: ${t.value};`),
	...tokens.radius.tokens.map((t) => `  --${t.name}: ${t.value};`),
	...tokens.size.tokens.map((t) => `  --${t.name}: ${t.value};`),
	...Object.entries(tokens.type.families).map(([name, family]) => `  --font-${name}: ${family};`),
];
const styles = tokens.type.groups.flatMap((group) =>
	group.styles.map(
		(s) =>
			`.text-${s.name} { font-family: var(--font-${group.family}); font-size: ${s.fontSize}; line-height: ${s.lineHeight}; font-weight: ${s.fontWeight};${s.letterSpacing ? ` letter-spacing: ${s.letterSpacing};` : ""} }`,
	),
);

const css = `/* Generated by scripts/build-tokens.mjs from the CleanOps design system (tokens.json v${tokens.version}). Do not edit. */
:root {
${[...lines("light"), ...fixed].join("\n")}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${lines("dark").join("\n")}
    color-scheme: dark;
  }
}
:root[data-theme="dark"],
[data-theme="dark"] {
${lines("dark").join("\n")}
  color-scheme: dark;
}
${styles.join("\n")}
`;
const target = new URL("../src/styles/tokens.css", import.meta.url).pathname;
writeFileSync(target, css);
console.log(`wrote ${target} (${tokens.color.tokens.length} colours)`);
